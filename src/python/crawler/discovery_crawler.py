"""## 6. Lưu trạng thái lên Drive (để resume)

Dùng 3 file dạng **append-only**, mỗi dòng 1 URL:

- `urls_found.txt`: mọi URL đã phát hiện (kể cả chưa crawl)
- `urls_done.txt`: URL đã crawl xong
- `urls_failed.txt`: URL lỗi quá `MAX_RETRIES` lần

Khi chạy lại: hàng đợi cần crawl = `found - done`. Dòng cuối bị ghi dở (do bị ngắt đột ngột) sẽ tự bị loại bỏ.
"""

import queue, threading

class CrawlStore:
    def __init__(self, data_dir):
        self.paths = {
            'found':  os.path.join(data_dir, 'urls_found.txt'),
            'done':   os.path.join(data_dir, 'urls_done.txt'),
            'failed': os.path.join(data_dir, 'urls_failed.txt'),
        }
        self.found_list = self._load('found')      # giữ thứ tự để BFS đúng thứ tự cũ
        self.found = set(self.found_list)
        self.done = set(self._load('done'))
        self.failed = set(self._load('failed'))

    def _load(self, kind):
        path = self.paths[kind]
        if not os.path.exists(path):
            return []
        with open(path, 'r', encoding='utf-8') as f:
            lines = f.readlines()
        # loại dòng cuối nếu bị ghi dở (không có \n)
        if lines and not lines[-1].endswith('\n'):
            lines = lines[:-1]
            with open(path, 'w', encoding='utf-8') as f:
                f.writelines(lines)
        return [l.strip() for l in lines if l.strip()]

    def add_found(self, url):
        self.found.add(url)
        self.found_list.append(url)

    def append(self, batch):
        """Ghi 1 batch [(kind, url), ...] xuống Drive."""
        grouped = {}
        for kind, url in batch:
            grouped.setdefault(kind, []).append(url)
        for kind in ('found', 'done', 'failed'):      # found luôn được ghi trước done
            urls = grouped.get(kind)
            if not urls:
                continue
            try:
                with open(self.paths[kind], 'a', encoding='utf-8') as f:
                    f.write(''.join(u + '\n' for u in urls))
                    f.flush()
                    os.fsync(f.fileno())
                logger.info(f'[writer] +{len(urls)} -> {os.path.basename(self.paths[kind])}')
            except OSError:
                logger.exception(f'[writer] ghi {kind} thất bại')

def writer_loop(store, write_q):
    stop = False
    while not stop:
        try:
            item = write_q.get(timeout=BATCH_TIMEOUT)
        except queue.Empty:
            continue
        batch = []
        if item is None:
            stop = True
        else:
            batch.append(item)
        while not stop and len(batch) < BATCH_SIZE:
            try:
                item = write_q.get_nowait()
            except queue.Empty:
                break
            if item is None:
                stop = True
                break
            batch.append(item)
        if batch:
            store.append(batch)

"""## 7. Logic crawl

Khác bản trước:
- Bỏ lệnh `Memory.forciblyPurgeJavaScriptMemory` (làm renderer của Edge bị treo/chết). Việc giải phóng RAM do restart driver đảm nhiệm.
- Tự phát hiện driver hỏng (lỗi liên tiếp) và restart; URL bị lỗi do driver hỏng **không** bị đánh dấu lỗi.
- Log lỗi gọn một dòng, không in traceback dài.
"""

import time, psutil
from collections import deque
from time import sleep
from selenium.webdriver.common.by import By
from selenium.common.exceptions import TimeoutException, WebDriverException

def standalize_url(url: str):
    if not url:
        return ""
    # Giữ lại số trang nếu là link danh mục (?page=), còn link sản phẩm thì cắt query param
    if '/c' in url and 'page=' in url:
        return url
    return url.split('?')[0].split('#')[0]

def short_err(e):
    msg = str(e).strip().splitlines()
    return f'{type(e).__name__}: {msg[0] if msg else ""}'

def get_driver_ram_mb(driver):
    """Tính tổng RAM thực của process Edge chính + các process con"""
    try:
        proc = psutil.Process(driver.service.process.pid)
        total = proc.memory_full_info().uss
        for child in proc.children(recursive=True):
            try:
                total += child.memory_full_info().uss
            except (psutil.NoSuchProcess, psutil.AccessDenied):
                continue
        return total / (1024 * 1024)
    except Exception:
        return None

def fmt_ram(ram):
    return f'{ram:.0f}MB' if ram is not None else 'n/a'

def scroll_down_page(driver):
    """Cuộn trang từng nấc để kích hoạt Lazy Loading của React/Next.js trên Tiki"""
    try:
        for step in [0.4, 0.8, 1.0]:
            driver.execute_script(f"window.scrollTo(0, document.body.scrollHeight * {step});")
            sleep(0.3)
    except Exception:
        pass

def producer_crawl(crawler, store, write_q, seed_urls, max_runtime_minutes=None):
    started = time.time()

    # --- KHỞI TẠO HOẶC RESUME TỪ DRIVE ---
    for seed in seed_urls:
        s_url = standalize_url(seed)
        if s_url not in store.found:
            store.add_found(s_url)
            write_q.put(('found', s_url))

    frontier = deque(u for u in store.found_list if u not in store.done)
    logger.info(f'Khởi động: found={len(store.found)} | done={len(store.done)} | hàng đợi={len(frontier)}')

    retries = {}
    pages_since_clear = 0
    pages_since_restart = 0
    consecutive_failures = 0
    restarts_without_success = 0

    while frontier:
        if max_runtime_minutes and (time.time() - started) / 60 >= max_runtime_minutes:
            logger.info('Hết thời gian chỉ định, dừng an toàn.')
            break

        url = frontier.popleft()
        if url in store.done:
            continue

        try:
            crawler.driver.get(url)
            scroll_down_page(crawler.driver)
            sleep(0.5)

            # --- 1. TỰ ĐỘNG BÓC CÁC DANH MỤC CON & MỞ RỘNG PHÂN TRANG (Nếu là trang danh mục) ---
            if '/c' in url:
                # Tự động quét các danh mục con trong menu/breadcrumb
                cat_elements = crawler.driver.find_elements(By.XPATH,
                    "//div[contains(@class, 'category') or contains(@class, 'Category') or contains(@class, 'filter')]//a[contains(@href, '/c')]"
                )
                for cat_el in cat_elements:
                    cat_href = cat_el.get_attribute('href')
                    if cat_href and 'tiki.vn' in cat_href and '/c' in cat_href:
                        clean_cat = standalize_url(cat_href)
                        if clean_cat not in store.found:
                            store.add_found(clean_cat)
                            frontier.append(clean_cat)
                            write_q.put(('found', clean_cat))

                # Tự động chuyển tiếp trang danh mục lên tới 50 trang (?page=1..50)
                curr_page = 1
                base_cat = url.split('?')[0]
                if 'page=' in url:
                    try:
                        curr_page = int(url.split('page=')[1].split('&')[0])
                    except Exception:
                        curr_page = 1
                if curr_page < 50:
                    next_page_url = f"{base_cat}?page={curr_page + 1}"
                    if next_page_url not in store.found:
                        store.add_found(next_page_url)
                        frontier.append(next_page_url)
                        write_q.put(('found', next_page_url))

            # --- 2. BÓC TÁCH LINK SẢN PHẨM ---
            elements = crawler.driver.find_elements(By.XPATH,
                "//a[contains(@class, 'product-item') or contains(@href, '-p')]"
            )
            raw_links = [el.get_attribute('href') for el in elements if el.get_attribute('href')]

        except (TimeoutException, WebDriverException) as e:
            consecutive_failures += 1
            logger.warning(f'Lỗi tải {url} ({consecutive_failures} lần liên tiếp) | {short_err(e)}')

            if consecutive_failures >= MAX_CONSECUTIVE_FAILURES:
                restarts_without_success += 1
                if restarts_without_success > MAX_RESTARTS_WITHOUT_SUCCESS:
                    frontier.appendleft(url)
                    logger.error('Driver lỗi liên tục nhiều lần, dừng crawler.')
                    break
                logger.warning('Nghi driver nghẽn -> Restart driver')
                try:
                    crawler.restart_driver()
                except Exception:
                    frontier.appendleft(url)
                    break
                consecutive_failures = 0
                pages_since_restart = 0
                pages_since_clear = 0
                frontier.appendleft(url)
                continue

            retries[url] = retries.get(url, 0) + 1
            if retries[url] <= MAX_RETRIES:
                frontier.append(url)
            else:
                store.done.add(url)
                store.failed.add(url)
                write_q.put(('failed', url))
                write_q.put(('done', url))
            continue

        consecutive_failures = 0
        restarts_without_success = 0

        # Lọc sạch và lưu các link sản phẩm (-p...html)
        for href in raw_links:
            if not href or 'tiki.vn' not in href or 'tka.tiki.vn' in href:
                continue
            clean_url = standalize_url(href)
            if '-p' in clean_url and clean_url.endswith('.html'):
                if clean_url in store.found:
                    continue
                store.add_found(clean_url)
                frontier.append(clean_url)
                write_q.put(('found', clean_url))

        # Đánh dấu xong URL hiện tại
        store.done.add(url)
        write_q.put(('done', url))

        pages_since_clear += 1
        pages_since_restart += 1

        # Dọn dẹp cache trình duyệt để kiểm soát bộ nhớ
        if pages_since_clear >= CLEAR_CACHE_EVERY_N_PAGES:
            try:
                crawler.driver.execute_cdp_cmd('Network.clearBrowserCache', {})
            except Exception:
                pass
            pages_since_clear = 0

        # Kiểm tra RAM và restart driver nếu vượt ngưỡng
        ram_mb = get_driver_ram_mb(crawler.driver)
        need_restart = pages_since_restart >= RESTART_DRIVER_EVERY_N_PAGES
        if ram_mb is not None and ram_mb > RESTART_DRIVER_RAM_MB:
            need_restart = True
        if need_restart:
            logger.info(f'Restarting driver định kỳ | RAM: {fmt_ram(ram_mb)}')
            try:
                crawler.restart_driver()
            except Exception:
                break
            pages_since_restart = 0
            pages_since_clear = 0

        logger.info(f'Frontier: {len(frontier)} | Found: {len(store.found)} | Done: {len(store.done)} | RAM: {fmt_ram(ram_mb)}')

class DiscoveryCrawler(BaseCrawler):
    def run(self, *args) -> None:
        seed_urls = args[0]
        store = CrawlStore(DATA_DIR)
        write_q = queue.Queue()

        writer = threading.Thread(target=writer_loop, args=(store, write_q), daemon=True)
        writer.start()
        try:
            producer_crawl(self, store, write_q, seed_urls, MAX_RUNTIME_MINUTES)
        finally:
            write_q.put(None)
            writer.join(timeout=60)
            logger.info(f'Kết thúc phiên: Found={len(store.found)} | Done={len(store.done)} | Failed={len(store.failed)}')

"""## 7b. (Chạy khi lần trước bị lỗi hàng loạt) Khôi phục URL bị đánh dấu lỗi oan

Nếu lần chạy trước driver bị hỏng, một số URL có thể đã bị ghi vào `urls_failed.txt` và `urls_done.txt` dù chưa crawl được. Cell này bỏ chúng khỏi `urls_done.txt` (có sao lưu `urls_done.backup.txt`) và xoá `urls_failed.txt`, để lần chạy tới crawl lại. Nếu `urls_failed.txt` trống hoặc không có thì cell không làm gì.
"""

failed_p = os.path.join(DATA_DIR, 'urls_failed.txt')
done_p   = os.path.join(DATA_DIR, 'urls_done.txt')

def _read(p):
    return [l.rstrip('\n') for l in open(p, encoding='utf-8')] if os.path.exists(p) else []

failed_urls = {u.strip() for u in _read(failed_p) if u.strip()}
if not failed_urls:
    print('Không có URL nào bị đánh dấu lỗi. Không cần khôi phục.')
else:
    done_lines = [u for u in _read(done_p) if u.strip()]
    shutil.copy2(done_p, os.path.join(DATA_DIR, 'urls_done.backup.txt'))
    kept = [u for u in done_lines if u.strip() not in failed_urls]
    with open(done_p, 'w', encoding='utf-8') as f:
        f.write(''.join(u + '\n' for u in kept))
        f.flush(); os.fsync(f.fileno())
    open(failed_p, 'w').close()
    print(f'Đã khôi phục {len(done_lines) - len(kept)} URL về hàng đợi (done: {len(done_lines)} -> {len(kept)}).')

