import subprocess, re, shutil, zipfile, io, urllib.request

def get_edge_version():
    out = subprocess.check_output(['microsoft-edge', '--version'], text=True)
    return re.search(r'(\d+\.\d+\.\d+\.\d+)', out).group(1)

def get_driver_version(path):
    if not os.path.exists(path):
        return None
    try:
        out = subprocess.check_output([path, '--version'], text=True, timeout=30)
        return re.search(r'(\d+\.\d+\.\d+\.\d+)', out).group(1)
    except Exception:
        return None

def http_get(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    with urllib.request.urlopen(req, timeout=180) as r:
        return r.read()

BASES = ['https://msedgedriver.microsoft.com', 'https://msedgedriver.azureedge.net']

def download_driver_zip(edge_ver):
    major = edge_ver.split('.')[0]
    versions = [edge_ver]
    tried = set()
    while versions:
        v = versions.pop(0)
        if v in tried:
            continue
        tried.add(v)
        for base in BASES:
            try:
                print(f'Thử tải driver {v} từ {base} ...')
                return http_get(f'{base}/{v}/edgedriver_linux64.zip')
            except Exception as e:
                print('  lỗi:', e)
        # không có đúng bản -> lấy bản mới nhất cùng major
        if len(tried) == 1:
            for base in BASES:
                try:
                    raw = http_get(f'{base}/LATEST_RELEASE_{major}_LINUX')
                    latest = raw.decode('utf-16').strip().lstrip('\ufeff')
                    versions.append(latest)
                    break
                except Exception as e:
                    print('  không lấy được LATEST_RELEASE:', e)
    raise RuntimeError('Không tải được Edge driver phù hợp')

def install_local_copy():
    shutil.copy2(f'{EDGE_DRIVER_DIR}/msedgedriver', DRIVER_PATH)
    os.chmod(DRIVER_PATH, 0o755)

edge_ver = get_edge_version()
edge_major = edge_ver.split('.')[0]
print('Edge version  :', edge_ver)

drive_driver = f'{EDGE_DRIVER_DIR}/msedgedriver'
driver_ver = None
if os.path.exists(drive_driver):
    install_local_copy()
    driver_ver = get_driver_version(DRIVER_PATH)
print('Driver (Drive):', driver_ver)

if driver_ver is None or driver_ver.split('.')[0] != edge_major:
    print('Driver thiếu hoặc lệch phiên bản -> tải mới')
    data = download_driver_zip(edge_ver)
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        z.extractall(EDGE_DRIVER_DIR)
    install_local_copy()
    driver_ver = get_driver_version(DRIVER_PATH)

print('Driver đang dùng:', driver_ver, '->', DRIVER_PATH)
assert driver_ver and driver_ver.split('.')[0] == edge_major, 'Driver và Edge không khớp phiên bản'

